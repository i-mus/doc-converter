// Regenerates src/convert/courierAfm.ts from pdfkit's Courier metrics.
// pdfmake's browser build ships Roboto only; embedding this one small file
// lets code blocks use the built-in monospace Courier font.
import { readFileSync, writeFileSync } from "node:fs";

const afm = readFileSync(
  new URL("../node_modules/@foliojs-fork/pdfkit/js/data/Courier.afm", import.meta.url),
  "utf8",
);
writeFileSync(
  new URL("../src/convert/courierAfm.ts", import.meta.url),
  `// Generated by scripts/make-courier-afm.mjs — do not edit.\nexport const COURIER_AFM = ${JSON.stringify(afm)};\n`,
);
console.log("wrote src/convert/courierAfm.ts", afm.length, "chars");
